function tb_text($heading, $body) {
    return ['acf_fc_layout' => 'text', 'heading' => $heading, 'body' => $body];
}
function tb_heading($heading) {
    return ['acf_fc_layout' => 'heading', 'heading' => $heading];
}
function tb_list($heading, $items) {
    return [
        'acf_fc_layout' => 'list',
        'heading'       => $heading,
        'items'         => array_map(fn($i) => ['item' => $i], $items),
    ];
}
function tb_note($body) {
    return ['acf_fc_layout' => 'note', 'body' => $body];
}

